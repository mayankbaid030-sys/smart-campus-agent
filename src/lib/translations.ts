export function getTranslation(lang: SupportedLanguage, key: string): string {
  const dict = UI_STRINGS[lang] || UI_STRINGS.en;
  return dict[key] || UI_STRINGS.en[key] || key;
}

export function getLanguageLabel(code: string): string {
  const matched = SUPPORTED_LANGUAGES.find(
    (l) => l.langCode === code || l.code === code || l.speechLang === code
  );
  return matched ? matched.nativeName : code;
}

export function isLanguageRtl(code: string): boolean {
  return code === 'ur' || code === 'ur-IN';
}
